/**
 * load-tests/helpers/payloads.js
 *
 * Synthetic payload generators.
 *
 * All generated email addresses use the `.invalid` TLD (RFC 2606 §2),
 * which is permanently reserved and can never be registered.  No real email
 * will be routed there under any circumstances.
 *
 * The `runId` parameter is a caller-supplied string (e.g. "load-1234567890")
 * that is constant within a test run.  Combined with k6's per-VU `__VU` and
 * per-iteration `__ITER` globals, every call generates a unique payload, so
 * no two requests share an idempotency key unless that is intentional.
 */

/**
 * Returns a unique, clearly synthetic email job payload.
 *
 * @param {string} runId - Stable identifier for the current test run.
 * @returns {{ to: string, subject: string, text: string }}
 */
export function emailPayload(runId) {
  return {
    to: `k6-vu${__VU}-iter${__ITER}-${runId}@loadtest.example.invalid`,
    subject: `[k6-load-test] run=${runId} vu=${__VU} iter=${__ITER}`,
    text: [
      "SYNTHETIC LOAD-TEST EMAIL — DO NOT DELIVER.",
      `Run ID : ${runId}`,
      `VU     : ${__VU}`,
      `Iter   : ${__ITER}`,
      "This message was generated by k6 and must not reach any real inbox.",
    ].join("\n"),
  };
}

/**
 * Returns a payload that the server must reject with HTTP 400.
 * Useful for validating that the validation layer is still active
 * under load.
 *
 * @returns {{ to: string, subject: string, text: string }}
 */
export function invalidEmailPayload() {
  return {
    to: "not-an-email-address",   // fails z.email()
    subject: "",                   // fails min(1)
    text: "",                      // fails min(1)
  };
}

/**
 * Returns a payload used for idempotency tests.
 * Two calls with the same `key` and `runId` return an identical payload,
 * allowing the duplicate-detection logic to be exercised.
 *
 * @param {string} runId
 * @param {string} key - A stable string that makes the payload unique to a scenario.
 * @returns {{ to: string, subject: string, text: string }}
 */
export function idempotentEmailPayload(runId, key) {
  return {
    to: `k6-idem-${key}-${runId}@loadtest.example.invalid`,
    subject: `[k6-idem] key=${key} run=${runId}`,
    text: `Idempotency test payload — key=${key} run=${runId}`,
  };
}
